"""The rule enforcer: every project.edit / project.write is checked against the project's own
rules before it lands, and a clear violation is blocked with the rule quoted.

Rules are the bullet points of RULES.md, AGENTS.md or CLAUDE.md at the project root (and in
.jevh/rules.md). A bullet can name where it applies with backticked globs before a colon;
`!glob` excludes. Without globs a rule applies everywhere:

    - `src/**`: log with the `log` module logger, never print().
    - `app/**`, `!app/repo.py`: views and services never run SQL directly; use app/repo.py.
    - `api/gen/**`: generated by `make gen` - never edit by hand.
    - Never put API keys or passwords in code; read them from environment variables.

Scope is plain code (evals/rule_cases.py): Jev's "does this rule apply to this file" ran opposite
to the truth, and a rule's wording is no guide to its scope. A scoped "never edit" rule blocks any
edit in scope without asking Jev (Jev scored those ~0.5). The rest are asked per rule: "does
`change` to `file` break `rule`?" - with scopes, 14/18 violations blocked and 0/30 good edits
blocked at 0.8 (tuning + held-out); it misses rules about something left out (missing type hints).
"""
from __future__ import annotations

import fnmatch
import os
import re
from dataclasses import dataclass, field
from pathlib import Path

RULE_FILES = ["RULES.md", "AGENTS.md", "CLAUDE.md", ".jevh/rules.md"]
BLOCK_AT = float(os.environ.get("JEVH_RULE_BLOCK", "0.8"))
MAX_RULES = 12          # rules asked about per edit (in scope); more -> the ones sharing words with the change
BREAKS_Q = "Does `change` to `file` break `rule`?"
BULLET_RE = re.compile(r"^\s*(?:[-*+]|\d+[.)])\s+(.+)$")
SCOPE_RE = re.compile(r"^((?:`[^`]+`\s*,?\s*)+):\s*(.+)$")
READ_ONLY_RE = re.compile(r"\b(?:never|do not|don't|must not|no)\s+(?:hand[- ])?(?:edit|modify|change|touch)|"
                          r"\bread[- ]only\b|\bnever edit", re.I)


@dataclass
class Rule:
    text: str
    source: str
    globs: list[str] = field(default_factory=list)

    def applies(self, rel: str) -> bool:
        inc = [g for g in self.globs if not g.startswith("!")]
        exc = [g[1:] for g in self.globs if g.startswith("!")]
        if inc and not any(_match(rel, g) for g in inc):
            return False
        return not any(_match(rel, g) for g in exc)

    @property
    def read_only(self) -> bool:
        return bool(self.globs) and bool(READ_ONLY_RE.search(self.text))


@dataclass
class Violation:
    rule: Rule
    p: float | None     # Jev's P(breaks); None = a read-only scope (no Jev call)

    def message(self, rel: str) -> str:
        why = "it is read-only there" if self.p is None else f"Jev: this change breaks it ({self.p:.2f})"
        return (f"Edit to {rel} blocked by the project's rules ({self.rule.source}): \"{self.rule.text}\" - {why}. "
                "Change the edit so it follows the rule. If the rule really does not apply to this change, pass "
                "rule_ok='why' to project.edit/write; the reason is reported to the user.")


def _match(rel: str, glob: str) -> bool:
    return fnmatch.fnmatch(rel, glob) or (glob.endswith("/**") and rel.startswith(glob[:-2]))


def parse(text: str, source: str) -> list[Rule]:
    rules = []
    in_code = False
    for line in text.splitlines():
        if line.strip().startswith("```"):
            in_code = not in_code
            continue
        m = BULLET_RE.match(line)
        if in_code or not m:
            continue
        body, globs = m.group(1).strip(), []
        s = SCOPE_RE.match(body)
        if s:
            globs = [g.strip() for g in re.findall(r"`([^`]+)`", s.group(1))]
            body = s.group(2).strip()
        if 12 <= len(body) <= 500:
            rules.append(Rule(body, source, globs))
    return rules


_cache: dict[str, tuple[float, list[Rule]]] = {}


def load(root: str | Path) -> list[Rule]:
    """The project's rules (re-read when a rules file changes)."""
    root = Path(root)
    files = [root / f for f in RULE_FILES if (root / f).is_file()]
    stamp = sum(f.stat().st_mtime for f in files)
    key = str(root)
    if key in _cache and _cache[key][0] == stamp:
        return _cache[key][1]
    rules = []
    for f in files:
        rules += parse(f.read_text(encoding="utf-8", errors="replace"), f.name)
    _cache[key] = (stamp, rules)
    return rules


def change_text(old: str, new: str, cap: int = 3000) -> str:
    """The change as -/+ lines, as the eval shows it to Jev: a small edit whole (old lines, then
    new), a big rewrite only the lines that differ."""
    import difflib
    a, b = old.splitlines(), new.splitlines()
    if len(a) + len(b) <= 80:
        text = "\n".join(["-" + ln for ln in a] + ["+" + ln for ln in b])
    else:
        text = "\n".join(ln[0] + ln[2:] for ln in difflib.ndiff(a, b) if ln[:2] in ("- ", "+ "))
    return text if len(text) <= cap else text[:cap] + f"\n[... {len(text) - cap} more chars]"


def _words(s: str) -> set[str]:
    return {w for w in re.findall(r"[a-z_]{3,}", s.lower())}


def check(root: str | Path, rel: str, old: str, new: str, existed: bool,
          ask=None) -> Violation | None:
    """The first rule the change breaks, or None. `ask(state) -> P(breaks)`; default: local Jev.
    Jev unreachable -> the edit goes through (the enforcer never blocks work on its own failure)."""
    rules = [r for r in load(root) if r.applies(rel)]
    if not rules:
        return None
    for r in rules:
        if r.read_only and existed:
            return Violation(r, None)
    rules = [r for r in rules if not r.read_only]
    change = change_text(old, new)
    if not change.strip():
        return None
    if len(rules) > MAX_RULES:
        words = _words(change + " " + rel)
        rules = sorted(rules, key=lambda r: -len(_words(r.text) & words))[:MAX_RULES]
    ask = ask or _ask_jev
    action = "changes an existing file" if existed else "creates a new file"
    best = None
    for r in rules:
        try:
            p = ask({"rule": r.text, "file": rel, "action": action, "change": change})
        except Exception:  # noqa: BLE001 - Jev down: never block on our own failure
            return None
        if p >= BLOCK_AT and (best is None or p > best.p):
            best = Violation(r, p)
    return best


def _ask_jev(state: dict) -> float:
    from jevh.decide import noul
    from jevh.tools._pick import client_from_env
    client, _ = client_from_env()
    return client.ask(state, {"breaks": noul(BREAKS_Q)})["breaks"].noul
