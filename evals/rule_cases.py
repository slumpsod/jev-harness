# Where each rule applies, as the rules file states it (`glob, !glob: rule`); none = everywhere.
# Scope is plain code: Jev's "does rule apply to file" ran opposite to the truth (it answered like
# "follows"), and a rule's wording is no guide (REPO names app/repo.py, the one file it exempts).
SCOPES = {LOGGER: ["src/**"], REPO: ["app/**", "!app/repo.py"], GENERATED: ["api/gen/**"],
          NETWORK: ["tests/**"], DEPS: ["requirements*.txt", "pyproject.toml"], AUTH: ["app/routes/**"],
          TYPES: ["lib/**"], MIGR: ["migrations/**"]}


def in_scope(rule: str, file: str) -> bool:
    globs = SCOPES.get(rule)
    if not globs:
        return True
    inc = [g for g in globs if not g.startswith("!")]
    exc = [g[1:] for g in globs if g.startswith("!")]
    return any(fnmatch.fnmatch(file, g) for g in inc) and not any(fnmatch.fnmatch(file, g) for g in exc)


