QUESTIONS = {
    "breaks": "Does `change` to `file` break `rule`?",
    "forbids": ("Does `change` do in `file` something `rule` forbids, or leave out something `rule` requires "
                "there? Answer no if `rule` does not apply to this file or this kind of change."),
    "applies": "Does `rule` apply to `file`?",
    "breaks_a": "Does this change (`action` `file`: `change`) break `rule`?",
}
COMBOS = [("applies", "breaks"), ("applies", "forbids"), ("applies", "breaks_a")]


def run_live(cases, raw: Path) -> list[dict]:
    cfg = load_config()
    c = SystemOneClient(cfg.jev["url"], cfg.jev["backend"], timeout=300)
    rows = []
    for rule, file, change, _ in cases:
        r = c.ask({"rule": rule, "file": file, "action": action(file), "change": change},
                  {k: noul(q) for k, q in QUESTIONS.items()})
        rows.append({k: r[k].noul for k in QUESTIONS})
    raw.write_text(json.dumps(rows, indent=1), encoding="utf-8")
    return rows


def report(cases, rows) -> None:
    labels = [c[3] for c in cases]
    for (rule, file, _, lab), s in zip(cases, rows):
        print(f"  {'BREAKS' if lab else 'ok    '}  " + "  ".join(f"{k}={v:.2f}" for k, v in s.items())
              + f"  {file[:28]:28} | {rule[:40]}")
    def show(name, blocked):
        hit = sum(b and l for b, l in zip(blocked, labels))
        false = sum(b and not l for b, l in zip(blocked, labels))
        return f"{name}: blocked {hit}/{labels.count(True)}, good edits blocked {false}/{labels.count(False)}"
    scoped = [in_scope(c[0], c[1]) for c in cases]
    for key in QUESTIONS:
        if key == "applies":
            continue
        print(f"\n== {key}: {QUESTIONS[key][:90]}")
        for t in (0.6, 0.7, 0.8, 0.85, 0.9, 0.95):
            print("  " + show(f"t={t:.2f}", [s[key] >= t for s in rows]) + "   | in scope only: "
                  + show("", [sc and s[key] >= t for s, sc in zip(rows, scoped)])[2:])


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--holdout", action="store_true")
    a = ap.parse_args()
    cases, raw = (HOLDOUT, RAW_HOLDOUT) if a.holdout else (CASES, RAW)
    rows = json.loads(raw.read_text(encoding="utf-8")) if a.offline else run_live(cases, raw)
    report(cases, rows)


if __name__ == "__main__":
    main()
