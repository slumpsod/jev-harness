"""The rule enforcer: project edits are checked against the project's RULES.md / AGENTS.md."""
import pytest

from jevh.tools import project, rules

RULES_MD = """# Project rules
- `src/**`: log with the `log` module logger, never print().
- `app/**`, `!app/repo.py`: views and services never run SQL directly; use app/repo.py.
- `api/gen/**`: generated by `make gen` - never edit by hand.
- Never put API keys or passwords in code; read them from environment variables.

```
- a bullet inside a code block is not a rule
```
"""


@pytest.fixture
def proj(tmp_path, monkeypatch):
    (tmp_path / "RULES.md").write_text(RULES_MD, encoding="utf-8")
    for rel, text in {"src/sync.py": "def run(n):\n    log.info('synced %d', n)\n",
                      "api/gen/client.py": "TIMEOUT = 10\n", "app/repo.py": "def q(): pass\n"}.items():
        (tmp_path / rel).parent.mkdir(parents=True, exist_ok=True)
        (tmp_path / rel).write_text(text, encoding="utf-8")
    monkeypatch.setattr(project, "root", str(tmp_path))
    monkeypatch.setattr(project, "_BACKUPS", tmp_path / ".bk")
    monkeypatch.setattr(project, "_touched", {})
    monkeypatch.setattr(project, "_overrides", [])
    rules._cache.clear()
    asked = []

    def fake_jev(state):
        asked.append(state)
        change = state["change"]
        if "print(" in change and "print()" in state["rule"]:
            return 0.99
        if "sk_live" in change and "API keys" in state["rule"]:
            return 0.98
        return 0.05
    monkeypatch.setattr(rules, "_ask_jev", fake_jev)
    return tmp_path, asked


def test_rules_are_parsed_with_their_scopes():
    rs = rules.parse(RULES_MD, "RULES.md")
    assert [r.globs for r in rs] == [["src/**"], ["app/**", "!app/repo.py"], ["api/gen/**"], []]
    assert rs[0].applies("src/sync.py") and not rs[0].applies("scripts/seed.py")
    assert rs[1].applies("app/views/orders.py") and not rs[1].applies("app/repo.py")
    assert rs[3].applies("anything/at/all.py")
    assert rs[2].read_only and not rs[0].read_only


def test_a_violation_is_blocked_with_the_rule_quoted_and_the_file_untouched(proj):
    root, _ = proj
    with pytest.raises(project.RuleViolation) as e:
        project.edit("src/sync.py", "    log.info('synced %d', n)", "    print(f'synced {n}')")
    assert "never print()" in str(e.value) and "RULES.md" in str(e.value)
    assert "log.info" in (root / "src/sync.py").read_text(encoding="utf-8")


def test_a_compliant_edit_goes_through(proj):
    root, asked = proj
    project.edit("src/sync.py", "log.info('synced %d', n)", "log.info('synced %d rows', n)")
    assert "rows" in (root / "src/sync.py").read_text(encoding="utf-8")
    assert {a["rule"][:10] for a in asked} == {"log with t", "Never put "}   # in-scope rules only


def test_out_of_scope_rules_are_not_asked(proj):
    _, asked = proj
    project.write("scripts/seed.py", "print('seeded')\n")          # print() is fine outside src/
    assert all("print()" not in a["rule"] for a in asked)
    assert asked and asked[0]["action"] == "creates a new file"


def test_read_only_scope_blocks_any_edit_without_asking_jev(proj):
    _, asked = proj
    with pytest.raises(project.RuleViolation, match="read-only"):
        project.edit("api/gen/client.py", "TIMEOUT = 10", "TIMEOUT = 30")
    assert not asked


def test_rule_ok_lets_an_edit_through_and_is_recorded(proj):
    root, _ = proj
    out = project.write("app/config.py", "KEY = 'sk_live_123'\n", rule_ok="a documented public test key")
    assert "wrote" in out and (root / "app/config.py").exists()
    assert project.overrides() == [{"file": "app/config.py", "rule": rules.load(root)[3].text,
                                    "why": "a documented public test key"}]


def test_jev_down_never_blocks(proj, monkeypatch):
    def down(state):
        raise ConnectionError("jev down")
    monkeypatch.setattr(rules, "_ask_jev", down)
    project.edit("src/sync.py", "    log.info('synced %d', n)", "    print(f'synced {n}')")


def test_no_rules_file_means_no_checks(tmp_path, monkeypatch):
    monkeypatch.setattr(project, "root", str(tmp_path))
    monkeypatch.setattr(project, "_BACKUPS", tmp_path / ".bk")
    monkeypatch.setattr(project, "_touched", {})
    rules._cache.clear()
    monkeypatch.setattr(rules, "_ask_jev", lambda s: pytest.fail("asked Jev without rules"))
    project.write("a.py", "print(1)\n")
